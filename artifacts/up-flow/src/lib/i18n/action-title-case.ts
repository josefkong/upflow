const SMALL_WORDS: Record<Language, ReadonlySet<string>> = {
  en: new Set(["a", "an", "and", "as", "at", "by", "for", "from", "of", "or", "the", "to", "via", "with", "without"]),
  "pt-BR": new Set(["a", "as", "ao", "aos", "à", "às", "com", "da", "das", "de", "do", "dos", "e", "em", "na", "nas", "no", "nos", "o", "os", "para", "por", "sem"]),
};

const ACTION_WORD_PATTERN = /\{[^}]+\}|\/\S+|[\p{L}\p{M}\p{N}]+(?:[-’'][\p{L}\p{M}\p{N}]+)*/gu;

export function titleCaseActionLabel(value: string, language: Language): string {
  if (!/\p{L}/u.test(value) || value === value.toLocaleUpperCase(language)) return value;

  let wordIndex = 0;
  return value.replace(ACTION_WORD_PATTERN, (word) => {
    if (word.startsWith("{") || word.startsWith("/")) return word;

    const currentIndex = wordIndex++;
    const normalized = word.toLocaleLowerCase(language);
    if (currentIndex > 0 && SMALL_WORDS[language].has(normalized)) {
      return normalized;
    }

    if (/\p{Lu}/u.test(word.slice(1))) return word;
    return `${word.charAt(0).toLocaleUpperCase(language)}${word.slice(1)}`;
  });
}

export function formatActionTranslation(
  key: string,
  value: string,
  language: Language,
): string {
  return ACTION_TITLE_KEYS.has(key)
    ? titleCaseActionLabel(value, language)
    : value;
}
